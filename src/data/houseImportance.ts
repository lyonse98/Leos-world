// when the two differ — discovery judges candidates by their
// Places/registry names ("&" vs "and", "Whaley House" vs
// "Whaley House Museum"), and the lookup must hit under either.
//
// This module stays backend-free like the other data modules:
// the place-key normalization is mirrored here rather than
// imported, so facts.ts never drags the Supabase client into
// its graph.

