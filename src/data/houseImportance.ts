/** backend.normalizePlaceKey, mirrored (see the note above). */
function importancePlaceKey(name: string): string {
  return name
    .trim()
    .toLowerCase()
    .replace(/[.'’]/g, '')
    .replace(/\s+/g, ' ');
}

/** The audit's importance record for the named place, or null when unaudited. */
export function houseImportanceFor(name: string): HouseImportance | null {
  const row = HOUSE_IMPORTANCE_DATA[importancePlaceKey(name)];
  if (!row) return null;
  return { verdict: row[0], story: row[1], people: row[2], portal: row[3] };
}
